import React, { useState } from 'react';
import ToolPage from '../../components/ToolPage';
import CodeEditor from '../../components/CodeEditor';
import CopyButton from '../../components/CopyButton';
import { Bot, Download, Check, ShieldAlert, Globe } from 'lucide-react';

interface BotRule {
  name: string;
  ua: string;
  allowed: boolean;
}

export default function RobotsGenerator() {
  const [defaultPolicy, setDefaultPolicy] = useState<'allow' | 'disallow'>('allow');
  const [sitemapUrl, setSitemapUrl] = useState<string>('https://example.com/sitemap.xml');
  const [crawlDelay, setCrawlDelay] = useState<number>(0);
  const [disallowedPaths, setDisallowedPaths] = useState<string>('/admin/\n/api/\n/tmp/\n/config/');

  const [bots, setBots] = useState<BotRule[]>([
    { name: 'Baidu (百度蜘蛛)', ua: 'Baiduspider', allowed: true },
    { name: 'Google (谷歌搜索)', ua: 'Googlebot', allowed: true },
    { name: 'Bing (微软必应)', ua: 'bingbot', allowed: true },
    { name: '360 Search (360搜索)', ua: '360Spider', allowed: true },
    { name: 'Sogou (搜狗搜索)', ua: 'Sogou web spider', allowed: true },
    { name: 'Yandex', ua: 'Yandex', allowed: false },
  ]);

  const toggleBot = (ua: string) => {
    setBots(
      bots.map((b) => (b.ua === ua ? { ...b, allowed: !b.allowed } : b))
    );
  };

  const generateRobots = () => {
    const lines: string[] = [];
    lines.push('# robots.txt generated by DevToolbox');
    lines.push('');

    // 全局默认策略
    lines.push('User-agent: *');
    if (defaultPolicy === 'disallow') {
      lines.push('Disallow: /');
    } else {
      const paths = disallowedPaths.split('\n').map((p) => p.trim()).filter(Boolean);
      if (paths.length > 0) {
        paths.forEach((p) => lines.push(`Disallow: ${p}`));
      } else {
        lines.push('Disallow:');
      }
    }

    if (crawlDelay > 0) {
      lines.push(`Crawl-delay: ${crawlDelay}`);
    }
    lines.push('');

    // 特殊蜘蛛定制规则
    bots.forEach((b) => {
      if (!b.allowed) {
        lines.push(`User-agent: ${b.ua}`);
        lines.push('Disallow: /');
        lines.push('');
      }
    });

    if (sitemapUrl.trim()) {
      lines.push(`Sitemap: ${sitemapUrl.trim()}`);
    }

    return lines.join('\n');
  };

  const robotsContent = generateRobots();

  const handleDownload = () => {
    const blob = new Blob([robotsContent], { type: 'text/plain;charset=utf-8' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = 'robots.txt';
    a.click();
  };

  return (
    <ToolPage
      title="Robots.txt 搜索引擎爬虫协议生成器"
      description="在线快速生成标准合规的 robots.txt 协议文件，精准配置百度、谷歌、必应等各引擎爬虫访问权限与 Sitemap"
    >
      <div className="space-y-6">
        <div className="grid grid-cols-1 lg:grid-cols-3 gap-6">
          {/* 左侧配置 */}
          <div className="lg:col-span-1 space-y-5 bg-white dark:bg-slate-800 p-5 rounded-xl border border-slate-200 dark:border-slate-700">
            <div>
              <label className="text-sm font-medium text-slate-700 dark:text-slate-300 mb-2 block">
                全局爬虫默认抓取策略
              </label>
              <div className="grid grid-cols-2 gap-2">
                <button
                  onClick={() => setDefaultPolicy('allow')}
                  className={`py-2 px-3 text-xs font-medium rounded-lg border transition-colors ${
                    defaultPolicy === 'allow'
                      ? 'bg-blue-50 dark:bg-blue-900/40 border-blue-500 text-blue-600 dark:text-blue-400'
                      : 'border-slate-200 dark:border-slate-700 text-slate-600 dark:text-slate-400'
                  }`}
                >
                  默认允许抓取 (除禁止目录)
                </button>
                <button
                  onClick={() => setDefaultPolicy('disallow')}
                  className={`py-2 px-3 text-xs font-medium rounded-lg border transition-colors ${
                    defaultPolicy === 'disallow'
                      ? 'bg-rose-50 dark:bg-rose-900/40 border-rose-500 text-rose-600 dark:text-rose-400'
                      : 'border-slate-200 dark:border-slate-700 text-slate-600 dark:text-slate-400'
                  }`}
                >
                  完全禁止所有抓取
                </button>
              </div>
            </div>

            {defaultPolicy === 'allow' && (
              <div className="space-y-2 pt-2 border-t border-slate-100 dark:border-slate-700/60">
                <label className="text-xs font-medium text-slate-700 dark:text-slate-300 block">
                  禁止抓取的私密目录 (Disallow: 每行一个)
                </label>
                <textarea
                  value={disallowedPaths}
                  onChange={(e) => setDisallowedPaths(e.target.value)}
                  rows={4}
                  className="w-full p-2.5 text-xs font-mono bg-slate-50 dark:bg-slate-900 border border-slate-200 dark:border-slate-700 rounded-lg focus:outline-none focus:border-blue-500"
                />
              </div>
            )}

            <div className="space-y-2 pt-2 border-t border-slate-100 dark:border-slate-700/60">
              <label className="text-xs font-medium text-slate-700 dark:text-slate-300 block">
                站点地图 (Sitemap URL)
              </label>
              <input
                type="text"
                value={sitemapUrl}
                onChange={(e) => setSitemapUrl(e.target.value)}
                placeholder="https://yourdomain.com/sitemap.xml"
                className="w-full px-3 py-1.5 text-xs bg-slate-50 dark:bg-slate-900 border border-slate-200 dark:border-slate-700 rounded-lg focus:outline-none focus:border-blue-500"
              />
            </div>

            <div className="space-y-2 pt-2 border-t border-slate-100 dark:border-slate-700/60">
              <label className="text-xs font-medium text-slate-700 dark:text-slate-300 block mb-1">
                知名搜索引擎爬虫许可控制
              </label>
              <div className="space-y-1.5">
                {bots.map((b) => (
                  <div
                    key={b.ua}
                    onClick={() => toggleBot(b.ua)}
                    className="flex items-center justify-between p-2 rounded-lg border border-slate-100 dark:border-slate-700/50 hover:bg-slate-50 dark:hover:bg-slate-700/30 cursor-pointer text-xs"
                  >
                    <span className="font-medium text-slate-700 dark:text-slate-300">{b.name}</span>
                    <span
                      className={`text-[11px] px-2 py-0.5 rounded font-medium ${
                        b.allowed
                          ? 'bg-emerald-50 dark:bg-emerald-950/40 text-emerald-600 dark:text-emerald-400'
                          : 'bg-rose-50 dark:bg-rose-950/40 text-rose-600 dark:text-rose-400'
                      }`}
                    >
                      {b.allowed ? '允许' : '屏蔽禁止'}
                    </span>
                  </div>
                ))}
              </div>
            </div>

            <button
              onClick={handleDownload}
              className="w-full py-2.5 px-4 bg-blue-600 hover:bg-blue-700 text-white font-medium rounded-lg shadow-sm flex items-center justify-center gap-2 transition-colors text-xs"
            >
              <Download className="w-4 h-4" />
              下载 robots.txt 文件
            </button>
          </div>

          {/* 右侧文件实时预览 */}
          <div className="lg:col-span-2 space-y-4">
            <div className="bg-white dark:bg-slate-800 rounded-xl border border-slate-200 dark:border-slate-700 overflow-hidden">
              <div className="p-3 bg-slate-50 dark:bg-slate-900 border-b border-slate-200 dark:border-slate-700 flex justify-between items-center">
                <span className="text-xs font-medium text-slate-600 dark:text-slate-300">
                  生成内容预览 (可直接复制部署至网站根目录)
                </span>
                <CopyButton text={robotsContent} label="复制全部内容" />
              </div>
              <CodeEditor value={robotsContent} readOnly minHeight="380px" />
            </div>
          </div>
        </div>
      </div>
    </ToolPage>
  );
}

