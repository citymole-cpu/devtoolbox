import { useState, useCallback, useEffect } from 'react';
import { ToolPage } from '../../components/ToolPage';
import { DualEditor } from '../../components/DualEditor';

const SAMPLE = `{
  "id": 1,
  "user_name": "devtoolbox",
  "active": true,
  "score": 95.5,
  "tags": ["go", "dev"],
  "address": {
    "city": "Beijing",
    "zip_code": "100000"
  },
  "items": [{ "name": "item1", "count": 3 }]
}`;

function toPascalCase(str: string): string {
  return str
    .replace(/[-_\s]+(.)?/g, (_, c) => (c ? c.toUpperCase() : ''))
    .replace(/^./, s => s.toUpperCase());
}

function goType(
  value: unknown,
  fieldNameHint: string,
  omitempty: boolean,
  structs: { name: string; code: string }[]
): string {
  if (value === null || value === undefined) return 'interface{}';
  if (typeof value === 'string') return 'string';
  if (typeof value === 'boolean') return 'bool';
  if (typeof value === 'number') {
    return Number.isInteger(value) ? 'int' : 'float64';
  }

  if (Array.isArray(value)) {
    if (value.length === 0) return '[]interface{}';
    const itemType = goType(value[0], fieldNameHint + 'Item', omitempty, structs);
    return `[]${itemType}`;
  }

  if (typeof value === 'object') {
    const structName = toPascalCase(fieldNameHint);
    generateStruct(value as Record<string, unknown>, structName, omitempty, structs);
    return structName;
  }

  return 'interface{}';
}

function generateStruct(
  obj: Record<string, unknown>,
  name: string,
  omitempty: boolean,
  structs: { name: string; code: string }[]
): void {
  const lines: string[] = [];
  lines.push(`type ${name} struct {`);

  for (const [key, value] of Object.entries(obj)) {
    const fieldName = toPascalCase(key);
    const fieldType = goType(value, fieldName, omitempty, structs);
    const tag = omitempty ? `\`json:"${key},omitempty"\`` : `\`json:"${key}"\``;
    lines.push(`\t${fieldName} ${fieldType} ${tag}`);
  }

  lines.push('}');
  structs.push({ name, code: lines.join('\n') });
}

function jsonToGo(jsonStr: string, structName: string, omitempty: boolean): string {
  const parsed = JSON.parse(jsonStr);
  const structs: { name: string; code: string }[] = [];

  if (typeof parsed === 'object' && parsed !== null && !Array.isArray(parsed)) {
    generateStruct(parsed, structName, omitempty, structs);
  } else if (Array.isArray(parsed) && parsed.length > 0 && typeof parsed[0] === 'object') {
    generateStruct(parsed[0] as Record<string, unknown>, structName, omitempty, structs);
  } else {
    return `// 顶层类型: ${goType(parsed, structName, omitempty, structs)}`;
  }

  // Reverse so main struct is first, nested later
  return structs.reverse().map(s => s.code).join('\n\n');
}

export default function JsonToGo() {
  const [input, setInput] = useState('');
  const [output, setOutput] = useState('');
  const [error, setError] = useState('');
  const [structName, setStructName] = useState('AutoGenerated');
  const [omitempty, setOmitempty] = useState(true);

  const convert = useCallback((text: string) => {
    if (!text.trim()) { setOutput(''); setError(''); return; }
    try {
      setOutput(jsonToGo(text, structName || 'AutoGenerated', omitempty));
      setError('');
    } catch (e: unknown) {
      setError(`转换错误: ${(e as Error).message}`);
      setOutput('');
    }
  }, [structName, omitempty]);

  useEffect(() => {
    const timer = setTimeout(() => convert(input), 300);
    return () => clearTimeout(timer);
  }, [input, convert]);

  return (
    <ToolPage title="JSON → Go Struct" description="将 JSON 转换为 Go 结构体定义">
      <div className="flex flex-wrap items-center gap-4 mb-4">
        <div className="flex items-center gap-2">
          <label className="text-sm text-gray-300">结构体名:</label>
          <input
            type="text"
            value={structName}
            onChange={e => setStructName(e.target.value)}
            className="bg-gray-700 text-gray-200 text-sm rounded px-2 py-1 border border-gray-600 focus:outline-none focus:border-blue-500 w-40"
          />
        </div>
        <label className="flex items-center gap-1.5 text-sm text-gray-300 cursor-pointer">
          <input
            type="checkbox"
            checked={omitempty}
            onChange={e => setOmitempty(e.target.checked)}
            className="rounded bg-gray-700 border-gray-600 text-blue-500 focus:ring-blue-500"
          />
          omitempty
        </label>
        <button
          onClick={() => setInput(SAMPLE)}
          className="px-3 py-1.5 text-sm bg-gray-600 hover:bg-gray-500 text-white rounded transition-colors ml-auto"
        >
          示例
        </button>
      </div>

      <DualEditor
        input={input}
        output={output}
        onInputChange={setInput}
        inputLabel="JSON"
        outputLabel="Go Struct"
        inputPlaceholder="请输入 JSON..."
        error={error}
      />
    </ToolPage>
  );
}
